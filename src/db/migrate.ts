import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { drizzle } from 'drizzle-orm/node-postgres';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { Pool } from 'pg';
import { env } from '../config/env'; // ← consistent with the rest of the codebase

const MIGRATIONS_DIR = 'src/db/migrations';

/**
 * Drizzle's migrator only applies migrations registered in
 * `meta/_journal.json`. Hand-written SQL files dropped into the folder (the
 * 0019+ pattern) are NOT journaled, so `migrate()` silently ignores them —
 * which is exactly how prod ended up missing `thumbnail_public_id`.
 *
 * This pass picks up every `*.sql` file that is NOT in the journal and applies
 * the ones that haven't run yet, tracked in `_manual_migrations`. Drop a new
 * numbered .sql file in and `db:migrate` applies it once. Make the SQL
 * idempotent (e.g. `ADD COLUMN IF NOT EXISTS`) as a belt-and-suspenders.
 */
async function runManualSql(pool: Pool, journaledTags: Set<string>) {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS "_manual_migrations" (
      "filename"   text PRIMARY KEY,
      "applied_at" timestamptz NOT NULL DEFAULT now()
    );
  `);

  const { rows } = await pool.query<{ filename: string }>(
    'SELECT filename FROM "_manual_migrations"',
  );
  const applied = new Set(rows.map((r) => r.filename));

  const pending = readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .filter((f) => !journaledTags.has(f.replace(/\.sql$/, ''))) // journaled → drizzle owns it
    .filter((f) => !applied.has(f))
    .sort(); // 0019 before 0020 — filename order is migration order

  if (pending.length === 0) {
    console.log('   no pending hand-written SQL');
    return;
  }

  for (const file of pending) {
    const sql = readFileSync(join(MIGRATIONS_DIR, file), 'utf8');
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query(sql);
      await client.query(
        'INSERT INTO "_manual_migrations" (filename) VALUES ($1)',
        [file],
      );
      await client.query('COMMIT');
      console.log(`   ✅ applied ${file}`);
    } catch (err) {
      await client.query('ROLLBACK');
      throw new Error(`manual migration ${file} failed: ${(err as Error).message}`);
    } finally {
      client.release();
    }
  }
}

async function runMigrations() {
  const pool = new Pool({
    host: env.DB_HOST,
    port: env.DB_PORT,
    user: env.DB_USER,
    password: env.DB_PASSWORD,
    database: env.DB_NAME,
    ssl: env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : undefined,
  });

  const db = drizzle(pool);

  try {
    // 1. Journaled migrations (0000–0018, generated by drizzle-kit).
    console.log('🔄 Running journaled migrations...');
    await migrate(db, { migrationsFolder: MIGRATIONS_DIR });
    console.log('✅ Journaled migrations complete');

    // 2. Hand-written SQL files outside the journal (0019+).
    console.log('🔄 Running hand-written SQL migrations...');
    const journal = JSON.parse(
      readFileSync(join(MIGRATIONS_DIR, 'meta', '_journal.json'), 'utf8'),
    ) as { entries: { tag: string }[] };
    const journaledTags = new Set(journal.entries.map((e) => e.tag));
    await runManualSql(pool, journaledTags);
    console.log('✅ Hand-written SQL migrations complete');
  } catch (err) {
    console.error('❌ Migration failed:', err);
    await pool.end();
    process.exit(1);
  }

  await pool.end();
}

runMigrations();
